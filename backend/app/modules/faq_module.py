def search_rules_knowledge(text: str) -> str:
    """
    搜索规则知识库，返回格式化的结构化答案。

    Args:
        text: 用户查询文本

    Returns:
        结构化答案，或 None
    """
    text_lower = text.lower()

    # 关键词匹配映射
    topic_map = {
        "永住": "永住权",
        "永住权": "永住权",
        "签证": "签证类型",
        "经营管理签证": "签证类型",
        "民宿合法": "民宿合法",
        "民宿许可": "民宿合法",
        "特区民宿": "民宿合法",
        "贷款条件": "外国人贷款",
        "外国人贷款": "外国人贷款",
        "海外投资者": "外国人贷款",
    }

    for kw, topic in topic_map.items():
        if kw in text_lower:
            kb = RULES_KNOWLEDGE.get(topic)
            if kb:
                lines = [f"📋 {topic}："]
                for sub_key, sub_val in kb.items():
                    lines.append(f"\n  【{sub_key}】{sub_val}")
                return "".join(lines)

    return None


def get_all_faq_terms() -> list:
    """
    获取所有 FAQ 术语列表

    Returns:
        术语列表
    """
    return list(FAQ_DATA.keys())


def search_faq(keyword: str) -> list:
    """
    搜索 FAQ

    Args:
        keyword: 关键词

    Returns:
        匹配的结果列表
    """
    keyword_lower = keyword.lower()
    results = []

    for term, answer in FAQ_DATA.items():
        if keyword_lower in term.lower() or keyword_lower in answer.lower():
            results.append({"term": term, "answer": answer})

    return results